-- 001_initial.sql — PostgreSQL translation of the complete NexusHOS SQLite schema.
--
-- Sources (SQLite DDL):
--   server/db.js               (core PMS + portfolio schema, indexes)
--   server/audit.js            (HMAC-chained append-only audit log)
--   server/security.js         (rate-limit buckets)
--   server/webhooks.js         (webhook subscriptions/events/delivery attempts)
--   server/routes/booking.js   (direct-booking quotes + idempotency)
--   server/routes/workflows.js (workflow automation + event outbox)
--
-- Deliberate compatibility decisions (keep a future async port behavior-identical):
--   * TEXT stays TEXT. JSON stored as TEXT stays TEXT (not JSONB). ISO 8601
--     timestamp strings stay TEXT (not TIMESTAMPTZ). The application compares
--     ISO strings lexicographically, which remains valid.
--   * Booleans stored as 0/1 integers stay INTEGER (with CHECK (x IN (0, 1))
--     where SQLite declared one); floats (REAL) become DOUBLE PRECISION.
--   * SQLite INTEGER PRIMARY KEY AUTOINCREMENT becomes
--     BIGINT GENERATED BY DEFAULT AS IDENTITY (BY DEFAULT so the SQLite data
--     pump can preserve existing sequence values).
--   * SQLite STRICT tables have no Postgres equivalent and are dropped;
--     Postgres column types already enforce affinity.
--   * SQLite RAISE(ABORT, ...) triggers become PL/pgSQL trigger functions that
--     RAISE EXCEPTION (see the append-only/immutability section below).
--
-- Multi-tenancy staging:
--   * Every BUSINESS table gains
--       organization_id TEXT NOT NULL DEFAULT 'org-default'
--       property_id     TEXT NOT NULL DEFAULT 'prop-default'
--     so existing INSERT statements keep working unchanged until the app layer
--     becomes tenant-aware. Tables that already carry property_id
--     (property_daily_metrics, group_bookings, reputation_reviews, esg_metrics,
--     esg_actions) gain organization_id only.
--   * NOT added to infra tables: sessions, audit_events (audit chain),
--     api_rate_limit_buckets, webhook_subscriptions/events/delivery_attempts
--     (webhook leases), workflow_event_outbox (leased outbox),
--     workflow_audit_events (append-only audit log), schema_migrations.
--   * NOT added to tenant-definition tables: organizations, properties,
--     user_property_memberships, users (global principals; tenancy is expressed
--     through user_property_memberships).

